"""Generate self-hosted Inter subsets without changing outlines or font axes.

Install scripts/fonts/requirements.txt in a virtual environment first.
The original public/fonts/InterVariable.woff2 remains the authoritative source.
"""

import argparse
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
import uharfbuzz as hb

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / 'public/fonts'
SOURCE = FONTS / 'InterVariable.woff2'
CSS = ROOT / 'src/styles/inter-fonts.css'


def character_sets():
    characters = set(TTFont(SOURCE).getBestCmap())
    # Keep complete words together, including Turkish and Vietnamese accents,
    # combining marks, currencies, punctuation, and the site's UI symbols.
    latin = {c for c in characters if (
        c <= 0x024F or 0x0300 <= c <= 0x036F or 0x1E00 <= c <= 0x1EFF
        or 0x2000 <= c <= 0x206F or 0x20A0 <= c <= 0x20CF
        or 0x2190 <= c <= 0x21FF
        or c in (0x2122, 0x2212, 0x2215, 0x266B, 0xFEFF, 0xFFFD)
    )}
    cyrillic = {c for c in characters if (
        0x0400 <= c <= 0x052F or 0x2DE0 <= c <= 0x2DFF
        or 0xA640 <= c <= 0xA69F
    )}
    # Preserve every other original character for place names, video titles,
    # and user-entered text, loading these glyphs only when actually needed.
    return {'latin': latin, 'cyrillic': cyrillic,
            'extended': characters - latin - cyrillic}


def unicode_ranges(characters):
    ranges = []
    for code in sorted(characters):
        if ranges and ranges[-1][1] + 1 == code:
            ranges[-1][1] = code
        else:
            ranges.append([code, code])
    return ', '.join(f'U+{start:04X}' + (f'-{end:04X}' if end != start else '')
                     for start, end in ranges)


def stylesheet(groups):
    output = '/* Generated by scripts/subset-fonts.py; do not edit by hand. */\n'
    for name, characters in groups.items():
        output += f'''\n@font-face {{
  font-family: "Inter";
  font-style: normal;
  font-weight: 100 900;
  font-display: swap;
  src: url("/fonts/InterVariable-{name}.woff2") format("woff2");
  unicode-range: {unicode_ranges(characters)};
}}
'''
    return output


def generate(groups):
    for name, characters in groups.items():
        font = TTFont(SOURCE, recalcTimestamp=False)
        options = subset.Options()
        # Keep discretionary alternates, kerning, numeric features, hinting,
        # optical sizing, weight variation, and embedded license metadata.
        options.layout_features = ['*']
        options.name_IDs = ['*']
        options.name_legacy = True
        options.name_languages = ['*']
        options.glyph_names = True
        options.notdef_outline = True
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=characters)
        subsetter.subset(font)
        font.flavor = 'woff2'
        font.save(FONTS / f'InterVariable-{name}.woff2')
    CSS.write_text(stylesheet(groups))


def shaping_font(font):
    buffer = BytesIO()
    font.flavor = None
    font.save(buffer)
    return hb.Font(hb.Face(buffer.getvalue())), font.getGlyphOrder()


def shape(font, names, text, variations, features=None):
    font.set_variations(variations)
    buffer = hb.Buffer()
    buffer.add_str(text)
    buffer.guess_segment_properties()
    hb.shape(font, buffer, features)
    return [(names[info.codepoint], info.cluster, position.x_advance,
             position.y_advance, position.x_offset, position.y_offset)
            for info, position in zip(buffer.glyph_infos, buffer.glyph_positions)]


def check(groups):
    original = TTFont(SOURCE)
    original_shaper, original_names = shaping_font(TTFont(SOURCE))
    assert CSS.read_text() == stylesheet(groups), 'Regenerate the font CSS'
    covered = set()
    for name, characters in groups.items():
        path = FONTS / f'InterVariable-{name}.woff2'
        font = TTFont(path)
        assert set(font.getBestCmap()) == characters, f'{name}: character coverage changed'
        assert not covered & characters, 'CSS ranges must not overlap'
        covered |= characters
        assert font.getTableData('fvar') == original.getTableData('fvar'), 'Font axes changed'
        for table in ('head', 'hhea', 'OS/2'):
            # Compare the metrics browsers use for line layout.
            for key in ('unitsPerEm', 'ascent', 'descent', 'lineGap',
                        'sTypoAscender', 'sTypoDescender', 'sTypoLineGap',
                        'usWinAscent', 'usWinDescent', 'sxHeight', 'sCapHeight'):
                if hasattr(original[table], key):
                    assert getattr(font[table], key) == getattr(original[table], key)
        def metadata(font):
            return {(n.nameID, n.platformID, n.platEncID, n.langID, n.toUnicode())
                    for n in font['name'].names}
        original_metadata = metadata(original)
        subset_metadata = metadata(font)
        assert subset_metadata <= original_metadata, 'Font names/license changed'
        assert {n for n in subset_metadata if n[0] <= 25} == {
            n for n in original_metadata if n[0] <= 25
        }, 'Font identity or license metadata lost'
        for glyph in font.getGlyphOrder():
            assert font['hmtx'][glyph] == original['hmtx'][glyph], 'Glyph metrics changed'
            assert font['glyf'][glyph].getCoordinates(font['glyf']) == original['glyf'][glyph].getCoordinates(
                original['glyf']
            ), f'{name}: outline changed for {glyph}'
            variations = font['gvar'].variations.get(glyph, [])
            reference = original['gvar'].variations.get(glyph, [])
            assert [(v.axes, v.coordinates) for v in variations] == [
                (v.axes, v.coordinates) for v in reference
            ], f'{name}: variable outline changed for {glyph}'
        shaper, names = shaping_font(font)
        # Check every mapped glyph at both optical-size extremes and the
        # intermediate weights used by the UI, not only default regular text.
        for weight, optical in ((100, 14), (400, 14), (650, 24), (750, 32), (900, 32)):
            variations = {'wght': weight, 'opsz': optical}
            for code in characters:
                text = chr(code)
                assert shape(shaper, names, text, variations) == shape(
                    original_shaper, original_names, text, variations
                ), f'{name}: glyph or spacing changed at U+{code:04X}'
            samples = [
                'AVATAR office ffi fl 0123456789 $€£¥₿ ↗ ♫',
                'Español Português Français Deutsch Italiano Türkçe',
                'Tiếng Việt: Giá Bitcoin Đổi tiền Ắ ề ự ỹ',
                'Ti\u0065\u0302\u0301ng Vie\u0323\u0302t',
                'Русский Биткоин Цена История рубль',
            ]
            for sample in samples:
                # Compare whole supported runs to verify kerning, ligatures,
                # combining marks and tabular prices as well as single glyphs.
                runs = ''.join(c if ord(c) in characters else '\n' for c in sample).splitlines()
                for text in filter(None, runs):
                    for features in (None, {'tnum': True}):
                        assert shape(shaper, names, text, variations, features) == shape(
                            original_shaper, original_names, text, variations, features
                        ), f'{name}: text shaping changed'
        print(f'{name}: {len(characters)} characters, {path.stat().st_size:,} bytes')
    assert covered == set(original.getBestCmap()), 'Original characters lost'
    print('All original characters, font axes, line metrics, shaping, and license metadata preserved.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify checked-in subsets without rewriting')
    args = parser.parse_args()
    groups = character_sets()
    if not args.check:
        generate(groups)
    check(groups)
